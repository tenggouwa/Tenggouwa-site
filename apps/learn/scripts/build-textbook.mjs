import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = resolve(root, 'src/content/chapters');
const course = readFileSync(resolve(root, 'src/data/course.ts'), 'utf8');
const ids = [...course.matchAll(/^    id: ['"]([^'"]+)['"],/gm)].map((m) => m[1]);
if (ids.length !== 18) throw new Error('Expected 18 lesson IDs');
const files = readdirSync(dir).filter((f) => f.endsWith('.md'));
if (files.length !== ids.length)
  throw new Error('Chapter count differs from curriculum');
const chapters = Object.fromEntries(
  ids.map((id) => {
    const body = readFileSync(resolve(dir, `${id}.md`), 'utf8').trim();
    if (body.length < 1800 || (body.match(/^### /gm) || []).length < 8)
      throw new Error(`Incomplete chapter: ${id}`);
    return [id, body];
  }),
);
const output =
  '// Generated by scripts/build-textbook.mjs. Edit src/content/chapters/*.md.\nexport const chapters: Record<string, string> = ' +
  JSON.stringify(chapters, null, 2) +
  ';\n';
const target = resolve(root, 'src/data/chapters.generated.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Textbook is stale. Run pnpm textbook.');
} else writeFileSync(target, output);
console.log(
  `Textbook: ${ids.length} chapters, ${Object.values(chapters).reduce((n, s) => n + s.length, 0)} characters`,
);
